"""
Иерархия доменных исключений платформы History Timeline.
Изолирована от фреймворка FastAPI, Pydantic и внешних библиотек.
"""


class DomainError(Exception):
    """
    Корневой базовый класс для всех исключений бизнес-логики и предметной области сервиса.
    Содержит человекочитаемое описание причины сбоя в атрибуте message.
    """

    def __init__(self, message: str = "Произошла ошибка доменной логики") -> None:
        # Сохранение текста сообщения в открытый атрибут для дальнейшей сериализации
        self.message: str = message
        # Инициализация стандартного базового класса Exception
        super().__init__(self.message)


class EventNotFoundError(DomainError):
    """
    Исключение, возникающее при попытке чтения, обновления или удаления
    исторического события по несуществующему первичному ключу.
    """

    def __init__(self, event_id: int) -> None:
        # Сохранение ID ненайденной сущности для контекста логирования
        self.event_id: int = event_id
        # Формирование информативного стандартизированного сообщения
        super().__init__(f"Историческое событие с ID {event_id} не найдено")


class InvalidDateRangeError(DomainError):
    """
    Исключение, возникающее при нарушении хронологических границ:
    дата окончания предшествует дате начала или переданные метки выходят
    за границы допустимой временной шкалы платформы.
    """

    def __init__(
        self,
        message: str = "Некорректный временной диапазон: дата окончания меньше даты начала или нарушены системные границы",
    ) -> None:
        super().__init__(message)


class InvalidParentRankError(DomainError):
    """
    Исключение, возникающее при нарушении иерархии рангов масштабирования событий:
    ранг родительского события должен быть строго более крупным по глубине детализации,
    чем ранг привязываемого дочернего события.
    """

    def __init__(
        self,
        message: str = "Нарушение иерархии рангов: родительское событие должно иметь строго более крупный масштаб детализации",
    ) -> None:
        super().__init__(message)


class DuplicateEventError(DomainError):
    """
    Исключение, возникающее при конфликте уникальности сущностей
    или попытке повторного добавления идентичной исторической записи.
    """

    def __init__(
        self,
        message: str = "Историческое событие с указанными параметрами уже существует в системе",
    ) -> None:
        super().__init__(message)


# Явное декларирование экспортируемых классов предметной области
__all__: list[str] = [
    "DomainError",
    "DuplicateEventError",
    "EventNotFoundError",
    "InvalidDateRangeError",
    "InvalidParentRankError",
]
