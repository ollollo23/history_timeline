from typing import Final

# Базовая системная единица измерения времени для всех временных меток проекта
TIME_UNIT: Final[str] = "seconds"
"""
Базовая системная единица измерения времени.
Поля start_date и end_date в системе хранят целое число секунд относительно
эпохи Unix (1970-01-01T00:00:00Z UTC), поддерживают отрицательные значения
для датировки исторических событий до нашей эры (BCE) и строго исключают дробную часть.
"""

# Целочисленные константы пересчета интервалов времени в секунды
SECONDS_PER_MINUTE: Final[int] = 60
SECONDS_PER_HOUR: Final[int] = 3600  # 60 * SECONDS_PER_MINUTE
SECONDS_PER_DAY: Final[int] = 86400  # 24 * SECONDS_PER_HOUR
SECONDS_PER_YEAR_AVG: Final[int] = (
    31557600  # Средний юлианский астрономический год: 365.25 суток по 86400 с
)
SECONDS_PER_CENTURY_AVG: Final[int] = 3155760000  # 100 * SECONDS_PER_YEAR_AVG (31557600 * 100)

# Параметры детерминированного мультипликативного хэширования выборки (метод Кнута)
RANGE_SAMPLE_HASH_MULTIPLIER: Final[int] = 2654435761
"""
Множитель мультипликативного хэширования Кнута (2^32 * (sqrt(5) - 1) / 2).
Используется для детерминированного равномерного перемешивания записей одинаковой
важности (одинаковый depth_level и длительность) в эндпоинте /range, исключая
хронологический перекос и мерцание маркеров при панорамировании усеченной выборки.

Обоснование отсутствия переполнения в PostgreSQL:
При первичном ключе id таблицы events типа INTEGER (максимум 2^31 - 1 = 2 147 483 647)
произведение (2^31 - 1) * 2654435761 равно 5 700 269 002 241 697 467, что строго
меньше максимального значения знакового 64-битного целого BIGINT
(2^63 - 1 = 9 223 372 036 854 775 807). Приведение id к BIGINT перед умножением
гарантирует отсутствие арифметического переполнения при вычислении хэша в SQL.
"""

RANGE_SAMPLE_HASH_MODULUS: Final[int] = 4294967296
"""
Модуль хэширования Кнута (2^32 = 4 294 967 296).
Ограничивает диапазон хэш-значений 32-битным беззнаковым целым числом,
обеспечивая равномерное распределение псевдослучайных весов событий.
"""

# Глобальные допустимые хронологические границы временной шкалы проекта
